'use strict';

// ★v2.16.2 — 사망이 **계속되는 동안** 경보를 주기적으로 다시 낸다(폴백 없는 구성 전용).
//
//   `제어되지 않습니다` 경보는 연속 실패 10회째에 **딱 한 번** 찍혔다. 그 뒤로는 읽기 실패가
//   전부 debug 이고(v2.4.5), 브릿지 재시작 예산(6회)까지 다 쓰면 하루 1줄 요약 말고는
//   **아무 줄도 안 나온다.** 기기는 여전히 죽어 있는데 로그는 조용하다.
//   2026-10-02 정수기 실사고 — 21:35 경보 1줄 뒤 4일간 침묵. NAS 감시기는 「사망 기록이
//   90분 넘게 갱신되지 않음」을 살았는지 죽었는지 가를 수 없어 판단을 보류했고,
//   그래서 첫 알림 뒤 재알림이 한 번도 가지 않았다.
//   ★로그 문구는 감시기의 API 다 — "죽어 있는 동안에는 사망 어휘가 끊기지 않는다"가 계약이다.
//
//   ⚠️주기는 **시간 기준**이다. 연속 실패 횟수는 요청 단위라 기기마다 속도가 다르다
//     (정수기 3분에 1회, 에어컨은 폴 한 번에 여러 회).
//   ⚠️60분 = 감시기의 신선도 창(90분)보다 짧아야 하고, 감시 주기(15분)를 한 번 놓쳐도 남아야 한다.
//   ⚠️폴백이 켜진 구성에는 걸지 않는다 — 거기서는 `클라우드로 대체` 줄이 계속 나오고
//     기기도 제어된다. 같은 상황을 두 어휘로 알리면 알림만 는다.
const DEAD_REANNOUNCE_MS = 60 * 60 * 1000;

/**
 * 사망 지속 줄. 어휘는 첫 경보와 같은 `제어되지 않습니다` 하나만 싣는다
 * (감시기는 한 줄에서 **마지막** 어휘를 집는다 — 다른 감시 어휘를 섞으면 판정이 바뀐다).
 */
function stillDeadLine(label, streak, sinceMs, now = Date.now()) {
  const min = sinceMs ? Math.max(1, Math.round((now - sinceMs) / 60000)) : 0;
  return `[${label}] 로컬 경로가 아직 응답하지 않습니다 (연속 실패 ${streak}회${min ? ` · ${min}분째` : ''}) `
    + '— 이 기기는 지금 제어되지 않습니다. 기기 전원과 IP를 확인하세요.';
}

module.exports = { DEAD_REANNOUNCE_MS, stillDeadLine };
